//! HTML exporters: scorecards and (later) the almanac.
//!
//! Output is standalone HTML with inline CSS so it can be shared anywhere.

use crate::core::types::World;
use crate::match_::state::{MatchPhase, MatchSnapshot};

/// Render a standalone HTML scorecard for a completed (or live) match.
pub fn scorecard_html(snap: &MatchSnapshot, world: &World) -> String {
    let team_name = |id: u32| -> String {
        world
            .teams
            .iter()
            .find(|t| t.id == id)
            .map(|t| t.name.clone())
            .unwrap_or_else(|| format!("Team {id}"))
    };
    let ground = world
        .grounds
        .iter()
        .find(|g| g.id == snap.ground_id)
        .map(|g| g.name.clone())
        .unwrap_or_else(|| format!("Ground {}", snap.ground_id));

    let mut innings_html = String::new();
    for (idx, inn) in snap.innings.iter().enumerate() {
        let cards: String = inn
            .batting_cards
            .iter()
            .map(|c| {
                let how = match &c.out {
                    Some(d) => format!("{:?}", d.out_type),
                    None => "not out".to_string(),
                };
                format!(
                    "<tr><td>{}</td><td>{}</td><td>{}</td><td>{}</td><td>{}x4</td><td>{}x6</td><td>SR {:.1}</td></tr>",
                    escape(&c.name),
                    c.runs,
                    c.balls,
                    how,
                    c.fours,
                    c.sixes,
                    if c.balls > 0 {
                        c.runs as f64 / c.balls as f64 * 100.0
                    } else {
                        0.0
                    }
                )
            })
            .collect();
        let bowls: String = inn
            .bowling_cards
            .iter()
            .map(|b| {
                format!(
                    "<tr><td>{}</td><td>{:.1}</td><td>{}</td><td>{}</td><td>{}</td></tr>",
                    escape(&b.name),
                    b.balls as f64 / 6.0,
                    b.maidens,
                    b.runs,
                    b.wickets
                )
            })
            .collect();
        innings_html.push_str(&format!(
            r#"<section class="innings">
<h3>{} — {}/{} in {:.1} overs</h3>
<table><thead><tr><th>Batter</th><th>R</th><th>B</th><th>How</th><th>4s</th><th>6s</th><th>SR</th></tr></thead>
<tbody>{}</tbody></table>
<table class="bowl"><thead><tr><th>Bowler</th><th>O</th><th>M</th><th>R</th><th>W</th></tr></thead>
<tbody>{}</tbody></table>
</section>"#,
            team_name(inn.batting_team_id),
            inn.runs,
            inn.wickets,
            inn.overs(),
            cards,
            bowls
        ));
        let _ = idx;
    }

    let status = if snap.phase == MatchPhase::Complete {
        snap.result
            .as_ref()
            .map(|r| r.summary.clone())
            .unwrap_or_else(|| "Complete".to_string())
    } else {
        "Match in progress".to_string()
    };

    format!(
        r#"<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<title>Scorecard — {} vs {}</title>
<style>
body {{ font-family: system-ui, sans-serif; background:#0d1117; color:#e6edf3; margin:2rem auto; max-width:900px; padding:0 1rem; }}
h1 {{ font-size:1.4rem; }} h2 {{ color:#8b949e; font-size:1rem; }}
table {{ border-collapse: collapse; width:100%; margin:.5rem 0 1.5rem; font-variant-numeric: tabular-nums; }}
th, td {{ border-bottom:1px solid #21262d; padding:.35rem .5rem; text-align:left; font-size:.9rem; }}
th {{ color:#8b949e; font-weight:600; }}
.result {{ background:#161b22; padding:.75rem 1rem; border-radius:8px; font-weight:600; }}
.innings {{ margin-top:1.5rem; }}
</style></head><body>
<h1>{} vs {}</h1>
<h2>{}</h2>
<p class="result">{}</p>
{}
<p style="color:#8b949e;font-size:.8rem">Generated by Captain's Call 2027 — tribute to Cricket Coach 2014. Player data is fictional.</p>
</body></html>"#,
        team_name(snap.home_team_id),
        team_name(snap.away_team_id),
        ground,
        status,
        team_name(snap.home_team_id),
        team_name(snap.away_team_id),
        innings_html
    )
}

fn escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}
