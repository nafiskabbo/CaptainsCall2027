//! Generate `src/lib/cc2014-assets.generated.ts` from the copied sprite folders.
//!
//! The loader uses explicit static imports rather than `import.meta.glob`,
//! because the UI e2e harness bundles to IIFE, where `import.meta` is empty.
//! A hand-maintained list would drift, so this generates it instead and the
//! loader fails loudly on an asset that is missing.
//!
//!   bun tools/gen-cc2014-assets.mjs

import { readdirSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const shotsDir = join(root, "src", "assets", "cc2014", "shots");
const outDir = join(root, "src", "assets", "cc2014", "outcomes");

for (const d of [shotsDir, outDir]) {
  if (!existsSync(d)) {
    console.error(`Missing ${d}. See THIRD-PARTY.md for how these get here.`);
    process.exit(1);
  }
}

const list = (d) => readdirSync(d).filter((f) => /\.(bmp|png)$/i.test(f)).sort();
const shots = list(shotsDir);
const outcomes = list(outDir);

if (shots.length === 0) throw new Error("no stroke sprites found");

const imports = [
  ...shots.map((f) => `import shot_${ident(f)} from "../assets/cc2014/shots/${f}";`),
  ...outcomes.map((f) => `import out_${ident(f)} from "../assets/cc2014/outcomes/${f}";`),
];

const entries = [
  ...shots.map((f) => `  "${f}": shot_${ident(f)},`),
  ...outcomes.map((f) => `  "${f}": out_${ident(f)},`),
];

const body = `// Generated by tools/gen-cc2014-assets.mjs. Do not edit.
//
// The copied Cricket Coach 2014 artwork, resolved to URLs at build time.
//
// See THIRD-PARTY.md: these files are the original's and are not licensed for
// redistribution. Delete this file and the folder together.

${imports.join("\n")}

/** Every copied sprite, keyed by filename. */
export const CC2014_ASSETS: Record<string, string> = {
${entries.join("\n")}
};
`;

const outPath = join(root, "src", "lib", "cc2014-assets.generated.ts");
writeFileSync(outPath, body);
console.log(`Wrote ${outPath}`);
console.log(`  ${shots.length} shot sprites, ${outcomes.length} outcome icons`);

/** A filename as a valid JS identifier. */
function ident(f) {
  return f.replace(/\.[^.]+$/, "").replace(/[^A-Za-z0-9_]/g, "_");
}